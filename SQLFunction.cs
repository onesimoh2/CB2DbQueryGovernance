using Microsoft.Data.SqlClient;
using System;
using System.Collections.Generic;
using System.ComponentModel;
using System.Text;
using System.Text.Json;

namespace CB2DbQueryGovernance
{
    internal class SQLFunction
    {
        // Executes an LLM-generated SQL query and returns the result as JSON.
        [Description("Generate the column description.")]
        public string ExecuteSqlToJson(string connectionString, [Description("The MS SQL string to be executed, this query has to be generated by the LLM and has to be either a selection of the content of a table or a selection of the schema of the table.")] string sqlQuery)
        {
            using (SqlConnection connection = new SqlConnection(connectionString))
            {
                try
                {
                    connection.Open();
                    using (SqlCommand command = new SqlCommand(sqlQuery, connection))
                    {
                        using (SqlDataReader reader = command.ExecuteReader())
                        {
                            var rows = new List<Dictionary<string, object>>();

                            // Loop through all records returned by the query
                            while (reader.Read())
                            {
                                var row = new Dictionary<string, object>();
                                for (int i = 0; i < reader.FieldCount; i++)
                                {
                                    string columnName = reader.GetName(i);
                                    object columnValue = reader.GetValue(i);

                                    // Convert DBNull to C# null so it exports nicely to JSON
                                    row[columnName] = columnValue == DBNull.Value ? null : columnValue;
                                }
                                rows.Add(row);
                            }

                            // Serialize the list of rows to a JSON string
                            return JsonSerializer.Serialize(rows, new JsonSerializerOptions { WriteIndented = true });
                        }
                    }
                }
                catch (Exception ex)
                {
                    return JsonSerializer.Serialize(new { error = ex.Message });
                }
            }
        }

        // Validates that the SQL query is intended to be read-only.
        // This validation is an additional guardrail, not a security boundary.
        // Real protection must be enforced at the database level by using a
        // dedicated account with read-only permissions on the required tables.
        public bool IsReadOnlySql(string sql)
        {
            if (string.IsNullOrWhiteSpace(sql))
                return false;

            string s = sql.Trim();

            // Only queries beginning with SELECT are allowed.
            if (!s.StartsWith("SELECT ", StringComparison.OrdinalIgnoreCase))
                return false;

            string upper = s.ToUpperInvariant();

            string[] forbidden =
            {
                "INSERT",
                "UPDATE",
                "DELETE",
                "INTO",
                "DROP",
                "ALTER",
                "CREATE",
                "TRUNCATE",
                "MERGE",
                "EXEC",
                "EXECUTE",
                "GRANT",
                "REVOKE",
                "DENY",
                "DBCC",
                "XP_"
            };
            // Reject commands that can modify, create, or administer database objects.
            return forbidden.All(x => !upper.Contains(x));
        }

    }

}
